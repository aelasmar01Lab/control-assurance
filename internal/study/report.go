func micros(d time.Duration) string { return fmt.Sprintf("%d µs", d.Microseconds()) }

func kib(n int64) string { return fmt.Sprintf("%.1f KiB", float64(n)/1024) }

func percent(part, whole int64) string {
	if whole == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%.1f%%", 100*float64(part)/float64(whole))
}

var kindNames = map[string]string{
	github.BranchRulesKind: "Branch rules (`github.branch_rules`)",
	aws.IAMCredentialsKind: "IAM credentials (`aws.iam_credentials`)",
}

func (r *Result) table(b *strings.Builder, get func(Strategy) Measurement) {
	base := get(NoDedup)
	b.WriteString("| Strategy | Observations | Payloads stored | Bytes stored | Of no-deduplication bytes | Median read | 95th percentile read | Evaluations reproduced |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for _, s := range Strategies {
		m := get(s)
		fmt.Fprintf(b, "| %s | %d | %d | %s | %s | %s | %s | %d of %d |\n", s, m.Observations, m.Payloads, kib(m.Bytes),
			percent(m.Bytes, base.Bytes), micros(m.MedianRead), micros(m.P95Read), m.Reproduced, m.Observations)
	}
}

// Markdown renders the case study. hardware describes the machine the read
// times were measured on.
func (r *Result) Markdown(hardware string) string {
	d := r.Dataset
	var b strings.Builder
	b.WriteString("# Deduplication case study\n\n")
	b.WriteString("Generated by `make study` (`cca study dedup`) from the harness in `internal/study`. Do not edit by hand.\n\n")
	b.WriteString("Counts and byte totals depend only on the dataset below and are the same on every machine; ")
	fmt.Fprintf(&b, "their fingerprint is `%s`, and a test fails if the committed fingerprint stops matching the harness. ", r.Fingerprint())
	b.WriteString("Read times depend on the machine and will differ from run to run.\n\n")

	b.WriteString("## Question\n\n")
	b.WriteString("The product stores a normalized evidence payload under the SHA-256 of its bytes, so collections of an unchanged ")
	b.WriteString("resource share one payload. What does that save against storing every collection, and against hashing the ")
	b.WriteString("response as it arrived? And does it cost anything on the way back out?\n\n")

	b.WriteString("## Dataset\n\n")
	b.WriteString("Entirely synthetic, generated from a fixed seed. No real repository, account or user appears in it.\n\n")
	b.WriteString("| Parameter | Value |\n| --- | --- |\n")
	fmt.Fprintf(&b, "| Seed | %d |\n", d.Seed)
	fmt.Fprintf(&b, "| Daily collections per resource | %d |\n", d.Days)
	fmt.Fprintf(&b, "| Repositories, each with 2 to 6 branch rules | %d |\n", d.Repositories)
	fmt.Fprintf(&b, "| Chance per repository per day that a rule changes | %.0f%% |\n", 100*d.RuleChangeChance)
	fmt.Fprintf(&b, "| Chance per collection that the same rules arrive in a different order, with different key order and white space | %.0f%% |\n", 100*d.ReorderChance)
	fmt.Fprintf(&b, "| AWS accounts, each with %d IAM users | %d busy, %d quiet |\n", d.UsersPerAcct, d.BusyAccounts, d.QuietAccounts)
	fmt.Fprintf(&b, "| Credential use in a busy account | 1 to 3 credentials every day |\n")
	fmt.Fprintf(&b, "| Credential use in a quiet account | 1 to 3 credentials on %.0f%% of days |\n", 100*d.QuietUseChance)
	b.WriteString("\n| Kind of evidence | Observations | Raw bytes | Normalized bytes |\n| --- | --- | --- | --- |\n")
	for _, k := range Kinds {
		fmt.Fprintf(&b, "| %s | %d | %s | %s |\n", kindNames[k], r.ByKind[NoDedup][k].Observations, kib(r.RawBytes[k]), kib(r.NormalizedBytes[k]))
	}
	b.WriteString("\nTwo assumptions shape the result and are not measurements of any real service:\n\n")
	b.WriteString("- **Reordering.** The dataset assumes the source sometimes returns the same rules in a different order. ")
	b.WriteString("How often GitHub does this, if at all, was not measured. With the chance set to zero, raw-byte and normalized hashing store the same number of branch-rule payloads.\n")
	b.WriteString("- **Activity.** The two kinds were chosen as opposites: configuration that rarely changes, and a report that changes whenever a credential is used.\n\n")

	b.WriteString("## Strategies\n\n")
	b.WriteString("- **No deduplication.** Every collection's raw response is written to its own file.\n")
	b.WriteString("- **Raw-byte hash.** The raw response is stored under the SHA-256 of its bytes; identical responses share a file.\n")
	b.WriteString("- **Normalized hash.** The response is normalized by the product's own normalizer, then stored under the SHA-256 of the normalized bytes. This is what the product does.\n\n")
	b.WriteString("Each strategy writes to a fresh directory through the product's filesystem evidence store, then reads every ")
	b.WriteString("observation back once in a fixed shuffled order. A read includes verifying the bytes against their SHA-256. ")
	b.WriteString("For the reproduction check, the product's checks (GH-01, GH-02, AWS-01, AWS-02) are re-applied to what was read back ")
	b.WriteString("and compared, result and explanation, with what they gave at collection. Raw payloads are normalized again first; that time is not part of the read time.\n\n")

	b.WriteString("## Results\n\n")
	for _, k := range Kinds {
		fmt.Fprintf(&b, "### %s\n\n", kindNames[k])
		r.table(&b, func(s Strategy) Measurement { return r.ByKind[s][k] })
		b.WriteString("\n")
	}
	b.WriteString("### Both kinds together\n\n")
	r.table(&b, func(s Strategy) Measurement { return r.Total[s] })

	b.WriteString("\n## What the numbers say\n\n")
	rules, creds := github.BranchRulesKind, aws.IAMCredentialsKind
	fmt.Fprintf(&b, "- For branch rules, %d collections reduced to %d payloads under the raw-byte hash and %d under the normalized hash. ",
		r.ByKind[NoDedup][rules].Observations, r.ByKind[RawHash][rules].Payloads, r.ByKind[NormalizedHash][rules].Payloads)
	b.WriteString("The gap between the two is the reordering assumption: normalization removes differences that carry no meaning.\n")
	fmt.Fprintf(&b, "- For IAM credentials, %d collections reduced to %d payloads under the raw-byte hash and %d under the normalized hash. ",
		r.ByKind[NoDedup][creds].Observations, r.ByKind[RawHash][creds].Payloads, r.ByKind[NormalizedHash][creds].Payloads)
	b.WriteString("Normalization does not reduce the count here, because the last-used dates that make one report differ from the next are exactly what the checks read. It reduces bytes only by dropping columns.\n")
	b.WriteString("- Deduplication pays where evidence describes configuration, and pays little where it describes activity. A busy account produces a new payload every day under any hash.\n")
	fmt.Fprintf(&b, "- Every strategy reproduced every evaluation (%d of %d under the normalized hash), so on this dataset none of the three loses anything a check reads.\n",
		r.Total[NormalizedHash].Reproduced, r.Total[NormalizedHash].Observations)

	b.WriteString("\n## What the normalizers keep and drop\n\n")
	b.WriteString("**Branch rules** (`" + github.BranchRulesNormalizer + "`). Keeps every field of every rule: `type`, `ruleset_id`, `ruleset_source`, ")
	b.WriteString("`ruleset_source_type` and `parameters`. Drops no field. It sorts rules by type then ruleset, sorts the keys of `parameters`, and removes insignificant white space. ")
	b.WriteString("It adds the repository, the default branch, the branch's `protected` flag, and whether the listing was read to the end.\n\n")
	b.WriteString("**IAM credentials** (`" + aws.IAMCredentialsNormalizer + "`). Keeps these credential report columns: ")
	b.WriteString("`" + strings.Join(aws.ReportColumnsKept, "`, `") + "`. Drops these: ")
	var dropped []string
	for _, col := range strings.Split(reportHeader, ",") {
		if !slices.Contains(aws.ReportColumnsKept, col) {
			dropped = append(dropped, col)
		}
	}
	b.WriteString("`" + strings.Join(dropped, "`, `") + "`. ")
	b.WriteString("From the account summary it keeps `AccountMFAEnabled` and `AccountAccessKeysPresent` and drops every other counter. ")
	b.WriteString("It sorts users by name. The report's generation time is not in the payload; it is stored on the observation as the source timestamp.\n\n")
	b.WriteString("A dropped field cannot be recovered later. If a future check needs one, the normalizer gets a new version, and evidence collected before it does not have the field.\n")

	b.WriteString("\n## Limits\n\n")
	b.WriteString("- The dataset is synthetic. The ratios follow from its parameters, above all the reordering and activity assumptions; they are not a forecast for a real estate.\n")
	b.WriteString("- Read times were taken on a local filesystem directly after writing, so the operating system's file cache is warm. They show that verification on read is cheap at this payload size, not what a cold disk or S3 would cost. The S3 backend was not measured.\n")
	b.WriteString("- Payloads here are a few kibibytes. Nothing is claimed about large payloads.\n")
	b.WriteString("- Raw-hash and no-deduplication storage keep fields the normalizer drops; the normalized strategy does not. The study measures size and reproduction, not the value of keeping the raw response.\n")

	b.WriteString("\n## Hardware\n\n")
	b.WriteString(hardware + ".\n")
	b.WriteString("\n## Reproduce\n\n")
	b.WriteString("```sh\nmake study   # regenerates this file; needs no database and no network\n```\n")
	return b.String()
}
