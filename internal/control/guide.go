package control

import (
	"fmt"
	"strings"

	"github.com/aelasmar01Lab/control-assurance/internal/pack"
)

// Guide renders the control and mapping guide as Markdown from the controls
// and tracking entries built into the binary.
func Guide(packs []*pack.Pack) string { return GuideFor(packs, All, Tracked) }

// GuideFor renders the guide for the given controls and tracking entries.
func GuideFor(packs []*pack.Pack, controls []Control, tracked []Tracking) string {
	mappedControls := func(framework, requirement string) []MappedControl {
		return mappedIn(controls, framework, requirement)
	}
	trackingFor := func(framework, requirement string) (Tracking, bool) {
		for _, t := range tracked {
			if t.Framework == framework && t.Requirement == requirement {
				return t, true
			}
		}
		return Tracking{}, false
	}
	var b strings.Builder
	b.WriteString("# Control and mapping guide\n\n")
	b.WriteString("Generated by `cca controls guide` from the files under `controls/`, `mappings/` and `tracking/`. Do not edit by hand; edit those files and run `make content`.\n\n")
	b.WriteString("Controls, mappings and tracking entries are drafted by an AI agent and reviewed by the maintainer. ")
	b.WriteString("Each is a **draft, not reviewed** until the maintainer signs it, and says so here. Nothing here has been reviewed by an auditor.\n\n")
	b.WriteString(LabScope + "\n\n")
	b.WriteString("A control is something the lab does to reduce a risk. A check is one narrow assertion over collected evidence ")
	b.WriteString("(see the [check guide](checks.md)). A mapping ties a control to a framework requirement and states how strong the tie is:\n\n")
	b.WriteString("- **direct**: the control, if supported, is what the requirement asks for. A direct mapping that is still a draft counts as partial.\n")
	b.WriteString("- **partial**: the control covers part of what the requirement asks for.\n")
	b.WriteString("- **supporting**: the control is related evidence, and does not establish the requirement.\n\n")
	reviewedControls, mappings, reviewedMappings := 0, 0, 0
	for _, c := range controls {
		if c.Review.IsReviewed() {
			reviewedControls++
		}
		for _, m := range c.Mappings {
			mappings++
			if m.Review.IsReviewed() {
				reviewedMappings++
			}
		}
	}
	fmt.Fprintf(&b, "Reviewed so far: %d of %d controls and %d of %d mappings.\n\n", reviewedControls, len(controls), reviewedMappings, mappings)

	b.WriteString("## How a control's state is derived\n\n")
	b.WriteString("The state is worked out on read and never stored. The first match wins:\n\n")
	b.WriteString("| State | When |\n| --- | --- |\n")
	b.WriteString("| Not evaluated | No check for the control has produced a result |\n")
	b.WriteString("| Needs attention | A current failure with no approved, unexpired exception; or manual evidence missing, rejected or awaiting review |\n")
	b.WriteString("| Stale | The newest evidence is older than the control's window, or accepted manual evidence is past its validity date |\n")
	b.WriteString("| Accepted risk | Every current failure is covered by an approved, unexpired exception |\n")
	b.WriteString("| Not evaluated | A check's current result could not be determined |\n")
	b.WriteString("| Supported | Every check passes on current evidence and manual evidence is accepted and valid |\n\n")
	b.WriteString("A collection failure is not an input. It adds no evidence, so the previous results stand and age toward stale.\n\n")

	b.WriteString("## Controls\n")
	for _, c := range controls {
		fmt.Fprintf(&b, "\n### %s (`%s`)\n\n", c.Title, c.Key)
		b.WriteString("| | |\n| --- | --- |\n")
		fmt.Fprintf(&b, "| Statement | %s |\n", c.Statement)
		fmt.Fprintf(&b, "| Review | **%s** |\n", c.Review.Label())
		fmt.Fprintf(&b, "| Domain and type | %s, %s |\n", c.Domain, c.Type)
		fmt.Fprintf(&b, "| Risk addressed | %s |\n", c.Risk)
		fmt.Fprintf(&b, "| Owner | %s |\n", c.Owner)
		fmt.Fprintf(&b, "| Evidence expected | %s |\n", c.EvidenceExpectation)
		rests := append([]string{}, c.Checks...)
		if c.ManualCheck != "" {
			rests = append(rests, fmt.Sprintf("%s (manual evidence, valid %d months)", c.ManualCheck, c.ManualValidityMonths))
		}
		fmt.Fprintf(&b, "| Rests on | %s |\n", strings.Join(rests, ", "))
		if c.Freshness > 0 {
			fmt.Fprintf(&b, "| Evidence window | %d hours |\n", int(c.Freshness.Hours()))
		}
		if len(c.Mappings) == 0 {
			b.WriteString("| Framework mapping | None yet. |\n")
		}
		for _, m := range c.Mappings {
			strength := m.Strength
			if m.EffectiveStrength() != m.Strength {
				strength += " (counted as " + m.EffectiveStrength() + " until reviewed)"
			}
			line := fmt.Sprintf("| Maps to %s %s | **%s**, %s. %s", m.Framework, m.Requirement, strength, m.Review.Label(), m.Rationale)
			if m.Limitation != "" {
				line += " **Limitation:** " + m.Limitation
			}
			b.WriteString(line + " |\n")
		}
	}

	for _, p := range packs {
		fmt.Fprintf(&b, "\n## Every %s requirement (%s)\n\n", p.Framework.Title, p.Framework.Version)
		b.WriteString("Each requirement is either covered in part by a control, or tracked with a reason. ")
		b.WriteString("\"Tracked manually\" means the work is done or judged outside this system, with no evidence held here. None of the three tracking statuses is a positive state.\n\n")
		b.WriteString("| Requirement | Covered by | Tracking | Review | Owner | Applicability | Evidence expected | Rationale |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n")
		for _, r := range p.Assessed() {
			var covered []string
			for _, m := range mappedControls(p.Framework.Key, r.ID) {
				covered = append(covered, fmt.Sprintf("%s (%s; %s)", m.Control.Title, m.Mapping.EffectiveStrength(), m.Mapping.Review.Label()))
			}
			if len(covered) > 0 {
				first := mappedControls(p.Framework.Key, r.ID)[0].Control
				fmt.Fprintf(&b, "| %s %s | %s | | | %s | Applicable. | See the control. | |\n", r.ID, requirementName(r), strings.Join(covered, ", "), first.Owner)
				continue
			}
			t, ok := trackingFor(p.Framework.Key, r.ID)
			if !ok {
				fmt.Fprintf(&b, "| %s %s | | **untracked** | | | | | |\n", r.ID, requirementName(r))
				continue
			}
			rationale := t.Rationale
			if t.Note != "" {
				rationale += " **Source note:** " + t.Note
			}
			fmt.Fprintf(&b, "| %s %s | | %s | %s | %s | %s | %s | %s |\n", r.ID, requirementName(r),
				strings.ReplaceAll(string(t.Status), "_", " "), t.Review.Label(), t.Owner, t.Applicability, t.EvidenceExpectation, rationale)
		}
	}
	return b.String()
}

// requirementName is what to call a requirement in a table: its title or
// label, or its text when the framework gives it neither.
func requirementName(r pack.Requirement) string {
	if n := r.Name(); n != "" {
		return n
	}
	return strings.ReplaceAll(r.Text, "|", "\\|")
}
