package control

import (
	"fmt"
	"strings"

	"github.com/aelasmar01Lab/control-assurance/internal/pack"
)

// Guide renders the control and mapping guide as Markdown from the control
// definitions and tracking entries in force.
func Guide(packs []*pack.Pack) string {
	var b strings.Builder
	b.WriteString("# Control and mapping guide\n\n")
	b.WriteString("Generated by `cca controls guide` from the definitions in `internal/control`. Do not edit by hand.\n\n")
	b.WriteString(LabScope + "\n\n")
	b.WriteString("A control is something the lab does to reduce a risk. A check is one narrow assertion over collected evidence ")
	b.WriteString("(see the [check guide](checks.md)). A mapping ties a control to a framework requirement and states how strong the tie is:\n\n")
	b.WriteString("- **direct**: the control, if supported, is what the requirement asks for. No mapping in this release is direct.\n")
	b.WriteString("- **partial**: the control covers part of what the requirement asks for.\n")
	b.WriteString("- **supporting**: the control is related evidence, and does not establish the requirement.\n\n")
	b.WriteString("No mapping has been reviewed by a second person yet, and each is labelled \"mapping not reviewed\" wherever it is shown.\n\n")

	b.WriteString("## How a control's state is derived\n\n")
	b.WriteString("The state is worked out on read and never stored. The first match wins:\n\n")
	b.WriteString("| State | When |\n| --- | --- |\n")
	b.WriteString("| Not evaluated | No check for the control has produced a result |\n")
	b.WriteString("| Needs attention | A current failure with no approved, unexpired exception; or manual evidence missing, rejected or awaiting review |\n")
	b.WriteString("| Stale | The newest evidence is older than the control's window, or accepted manual evidence is past its validity date |\n")
	b.WriteString("| Accepted risk | Every current failure is covered by an approved, unexpired exception |\n")
	b.WriteString("| Not evaluated | A check's current result could not be determined |\n")
	b.WriteString("| Supported | Every check passes on current evidence and manual evidence is accepted and valid |\n\n")
	b.WriteString("A collection failure is not an input. It adds no evidence, so the previous results stand and age toward stale.\n\n")

	b.WriteString("## Controls\n")
	for _, c := range All {
		fmt.Fprintf(&b, "\n### %s (`%s`)\n\n", c.Title, c.Key)
		b.WriteString("| | |\n| --- | --- |\n")
		fmt.Fprintf(&b, "| Risk addressed | %s |\n", c.Risk)
		fmt.Fprintf(&b, "| Owner | %s |\n", c.Owner)
		fmt.Fprintf(&b, "| Evidence expected | %s |\n", c.EvidenceExpectation)
		rests := append([]string{}, c.Checks...)
		if c.ManualCheck != "" {
			rests = append(rests, fmt.Sprintf("%s (manual evidence, valid %d months)", c.ManualCheck, c.ManualValidityMonths))
		}
		fmt.Fprintf(&b, "| Rests on | %s |\n", strings.Join(rests, ", "))
		if c.Freshness > 0 {
			fmt.Fprintf(&b, "| Evidence window | %d hours |\n", int(c.Freshness.Hours()))
		}
		if len(c.Mappings) == 0 {
			b.WriteString("| Framework mapping | None. No framework in this release has a requirement this control maps to. |\n")
		}
		for _, m := range c.Mappings {
			reviewed := "not reviewed"
			if m.ReviewedBy != "" {
				reviewed = "reviewed by " + m.ReviewedBy
			}
			fmt.Fprintf(&b, "| Maps to %s %s | **%s**, %s. %s **Limitation:** %s |\n", m.Framework, m.Requirement, m.Strength, reviewed, m.Rationale, m.Limitation)
		}
	}

	for _, p := range packs {
		fmt.Fprintf(&b, "\n## Every %s requirement (%s)\n\n", p.Framework.Title, p.Framework.Version)
		b.WriteString("Each requirement is either covered in part by a control, or tracked with a reason. ")
		b.WriteString("\"Tracked manually\" means the work is done or judged outside this system, with no evidence held here. None of the three tracking statuses is a positive state.\n\n")
		b.WriteString("| Requirement | Covered by | Tracking | Owner | Applicability | Evidence expected | Rationale |\n| --- | --- | --- | --- | --- | --- | --- |\n")
		for _, r := range p.Requirements {
			var covered []string
			for _, m := range MappedControls(p.Framework.Key, r.ID) {
				covered = append(covered, fmt.Sprintf("%s (%s)", m.Control.Title, m.Mapping.Strength))
			}
			if len(covered) > 0 {
				first := MappedControls(p.Framework.Key, r.ID)[0].Control
				fmt.Fprintf(&b, "| %s %s | %s | | %s | Applicable. | See the control. | |\n", r.ID, r.Title, strings.Join(covered, ", "), first.Owner)
				continue
			}
			t, ok := TrackingFor(p.Framework.Key, r.ID)
			if !ok {
				fmt.Fprintf(&b, "| %s %s | | **untracked** | | | | |\n", r.ID, r.Title)
				continue
			}
			rationale := t.Rationale
			if t.Note != "" {
				rationale += " **Source note:** " + t.Note
			}
			fmt.Fprintf(&b, "| %s %s | | %s | %s | %s | %s | %s |\n", r.ID, r.Title,
				strings.ReplaceAll(string(t.Status), "_", " "), t.Owner, t.Applicability, t.EvidenceExpectation, rationale)
		}
	}
	return b.String()
}
