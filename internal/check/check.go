// Package check holds the versioned checks. A check is one narrow assertion
// over one observation, with its limits stated.
package check

import (
	"fmt"
	"sort"
	"strings"
	"time"
)

// Result is the outcome of applying a check to an observation.
type Result string

// The three results. A collection failure is none of them: it is recorded on
// the run and produces no evaluation.
const (
	Pass         Result = "pass"
	Fail         Result = "fail"
	NotEvaluated Result = "not_evaluated"
)

// Check is one version of one check. Once a version has produced an
// evaluation its fields must not change; change the Version instead.
type Check struct {
	Key     string
	Version string
	// ObservationKind is the kind of observation this check reads.
	ObservationKind string
	// Assertion is the single statement a pass asserts.
	Assertion string
	// Source is the API call the evidence comes from.
	Source string
	// Permission is the read access the collector needs.
	Permission string
	// Establishes is what a pass shows.
	Establishes string
	// DoesNotEstablish is what a pass does not show.
	DoesNotEstablish string
	// Control is the internal control the check supports.
	Control string
	// Mapping is the framework requirement and the strength of the mapping.
	Mapping string
	// Eval applies the check to one stored observation. It is nil for a
	// manual check. It must depend on nothing but its input, so that an
	// evaluation can be reproduced from the stored observation.
	Eval func(in Input) (Result, string, error)
	// Manual marks a check whose evidence is submitted and reviewed by
	// people. It has no Eval; its state is derived from the reviewed
	// submissions of its control.
	Manual bool
}

// Input is the stored observation a check is applied to.
type Input struct {
	// Payload is the evidence, as stored.
	Payload []byte
	// AsOf is the moment the evidence describes: the source's own
	// timestamp when it gave one, otherwise the time of collection. A check
	// that measures an age measures it to this moment, never to the clock.
	AsOf time.Time
}

// REC01 is the manual-evidence check for the backup and recovery control.
const REC01 = "REC-01"

var rec01 = Check{
	Key:              REC01,
	Version:          "1",
	ObservationKind:  "manual.evidence_submission",
	Assertion:        "A recovery exercise record was accepted within the last 12 months.",
	Source:           "Manual evidence: a dated recovery exercise record, submitted by the control owner",
	Permission:       "None. A reviewer who is not the submitter accepts or rejects the record",
	Establishes:      "A reviewer accepted a dated record of a recovery exercise.",
	DoesNotEstablish: "That recovery would succeed today.",
	Control:          "Backup and recovery",
	Mapping:          "MVSP 4.4, partial.",
	Manual:           true,
}

var registry = []Check{gh01, gh02, gh03, gh04, aws01, aws02, aws03, aws04, rec01}

// Automated returns the checks the evaluator runs against observations.
func Automated() []Check {
	var out []Check
	for _, c := range All() {
		if !c.Manual {
			out = append(out, c)
		}
	}
	return out
}

// All returns every registered check, ordered by key then version.
func All() []Check {
	out := append([]Check(nil), registry...)
	sort.Slice(out, func(i, j int) bool {
		if out[i].Key != out[j].Key {
			return out[i].Key < out[j].Key
		}
		return out[i].Version < out[j].Version
	})
	return out
}

// Lookup returns the check with the given key and version.
func Lookup(key, version string) (Check, bool) {
	for _, c := range registry {
		if c.Key == key && c.Version == version {
			return c, true
		}
	}
	return Check{}, false
}

// Guide renders the check guide as Markdown, straight from the definitions
// the evaluator runs, so the document cannot drift from behaviour.
func Guide() string {
	var b strings.Builder
	b.WriteString("# Check guide\n\n")
	b.WriteString("Generated by `cca checks guide` from the check definitions in `internal/check`. Do not edit by hand.\n\n")
	b.WriteString("A check result is one of `pass`, `fail` or `not_evaluated`. A collection failure is none of these: ")
	b.WriteString("it is recorded on the collection run and produces no result.\n")
	for _, c := range All() {
		fmt.Fprintf(&b, "\n## %s (version %s)\n\n", c.Key, c.Version)
		fmt.Fprintf(&b, "| | |\n| --- | --- |\n")
		fmt.Fprintf(&b, "| Assertion | %s |\n", c.Assertion)
		fmt.Fprintf(&b, "| Evidence source | %s |\n", c.Source)
		fmt.Fprintf(&b, "| Read permission | %s |\n", c.Permission)
		fmt.Fprintf(&b, "| A pass establishes | %s |\n", c.Establishes)
		fmt.Fprintf(&b, "| A pass does not establish | %s |\n", c.DoesNotEstablish)
		fmt.Fprintf(&b, "| Internal control | %s |\n", c.Control)
		fmt.Fprintf(&b, "| Framework mapping | %s |\n", c.Mapping)
	}
	return b.String()
}
